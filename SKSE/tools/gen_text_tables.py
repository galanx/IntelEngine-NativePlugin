#!/usr/bin/env python3
"""The two tables the DLL reads text with, written as headers.

    SKSE/src/CodePageTables.h    what each byte from 0x80 up means in the Windows code pages that old plugins and old
                                 translations were saved in (1250 Central European, 1251 Cyrillic, 1252 Western,
                                 1253 Greek, 1254 Turkish, 1257 Baltic). Taken from Windows itself
                                 (MultiByteToWideChar), so a byte reads here as it reads everywhere else on the PC.
    SKSE/src/LetterFoldTable.h   the plain letter of every Latin, Greek and Cyrillic letter: lower case, without its
                                 marks (from Python's Unicode data), for comparing names (LetterFold.h).

    python SKSE/tools/gen_text_tables.py [--check]

--check compares with the files as they are and fails when one is out of date. Windows only (the code pages are asked
of the system).
"""
import ctypes
import io
import os
import sys
import unicodedata

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.normpath(os.path.join(HERE, "..", "src"))

PAGES = [1250, 1251, 1252, 1253, 1254, 1257]


def page_table(page):
    out = []
    buf = ctypes.create_unicode_buffer(4)
    for byte in range(0x80, 0x100):
        n = ctypes.windll.kernel32.MultiByteToWideChar(page, 0, bytes([byte]), 1, buf, 4)
        if n != 1:
            raise SystemExit(f"code page {page}: byte {byte:#x} gave {n} units")
        out.append(ord(buf[0]))
    return out


def rows(values, per=12, width=6):
    lines = []
    for i in range(0, len(values), per):
        lines.append("        " + ", ".join(f"0x{v:0{width - 2}X}" for v in values[i:i + per]) + ",")
    return "\n".join(lines)


def code_pages_header():
    parts = [
        "#pragma once",
        "",
        "// Generated by SKSE/tools/gen_text_tables.py: do not edit. What each byte from 0x80 to 0xFF means in the Windows",
        "// code pages old plugins and translations were saved in, as Windows itself reads them (GameText.h).",
        "",
        "#include <cstdint>",
        "",
        "namespace IntelEngine::CodePageTables {",
        "",
    ]
    for page in PAGES:
        parts.append(f"    inline constexpr std::uint16_t k{page}[128] = {{")
        parts.append(rows(page_table(page)))
        parts.append("    };")
        parts.append("")
    parts.append("    // The table of a page, or null for a page that is not here.")
    parts.append("    inline constexpr const std::uint16_t* Of(int page) {")
    parts.append("        switch (page) {")
    for page in PAGES:
        parts.append(f"            case {page}: return k{page};")
    parts.append("            default: return nullptr;")
    parts.append("        }")
    parts.append("    }")
    parts.append("}")
    return "\n".join(parts) + "\n"


# Letters that have no mark to take off but a plainer spelling all the same.
SPECIAL = {
    "ß": "ss", "ẞ": "ss", "æ": "ae", "œ": "oe", "ø": "o", "đ": "d", "ð": "d",
    "þ": "th", "ł": "l", "ħ": "h", "ı": "i", "ĸ": "k", "ŀ": "l", "ŋ": "n",
    "ŧ": "t", "ſ": "s", "ĳ": "ij", "ŉ": "n", "ƒ": "f", "ǆ": "dz", "ǉ": "lj",
    "ǌ": "nj", "ǳ": "dz", "ǣ": "ae", "ǽ": "ae", "ǿ": "o", "ƀ": "b", "ƙ": "k",
    "ƚ": "l", "ƫ": "t", "ǥ": "g", "ɉ": "j", "ɍ": "r", "ȼ": "c", "ƈ": "c",
    "ς": "σ",   # the sigma that ends a word is a sigma
    "ʼ": "'", "ʹ": "'", "ʻ": "'",   # the apostrophes among the modifier letters
}


def fold(cp):
    ch = chr(cp)
    if unicodedata.combining(ch):
        return ""   # a mark standing by itself after its letter: left out
    low = ch.lower()
    out = []
    for c in unicodedata.normalize("NFD", low):
        if unicodedata.combining(c):
            continue
        out.append(SPECIAL.get(c, c))
    text = "".join(out)
    if len(text) > 2 or any(ord(c) > 0xFFFF for c in text):
        return ch
    return text


def fold_range(first, end):
    firsts, more = [], []
    for cp in range(first, end):
        text = fold(cp)
        if text == "":
            firsts.append(0)
            continue
        firsts.append(ord(text[0]))
        if len(text) == 2:
            more.append((cp, ord(text[1])))
    return firsts, more


RANGES = [("A", 0x00C0, 0x0530), ("B", 0x1E00, 0x2000)]


def letter_fold_header():
    parts = [
        "#pragma once",
        "",
        "// Generated by SKSE/tools/gen_text_tables.py: do not edit. The plain letter of every Latin, Greek and Cyrillic",
        "// letter (lower case, without its marks); 0: a mark by itself, left out. kMore: the letters that become two",
        "// (their second letter). Read by LetterFold.h.",
        "",
        "#include <cstdint>",
        "",
        "namespace IntelEngine::LetterFoldTable {",
        "",
    ]
    all_more = []
    for name, first, end in RANGES:
        firsts, more = fold_range(first, end)
        all_more += more
        parts.append(f"    inline constexpr char32_t kFirst{name} = 0x{first:04X}, kEnd{name} = 0x{end:04X};")
        parts.append(f"    inline constexpr std::uint16_t k{name}[0x{end - first:X}] = {{")
        parts.append(rows(firsts))
        parts.append("    };")
        parts.append("")
    parts.append("    struct More {")
    parts.append("        std::uint16_t letter, second;")
    parts.append("    };")
    parts.append(f"    inline constexpr More kMore[{len(all_more)}] = {{")
    line = []
    for cp, second in sorted(all_more):
        line.append(f"{{0x{cp:04X}, 0x{second:04X}}}")
        if len(line) == 6:
            parts.append("        " + ", ".join(line) + ",")
            line = []
    if line:
        parts.append("        " + ", ".join(line) + ",")
    parts.append("    };")
    parts.append("}")
    return "\n".join(parts) + "\n"


def main():
    check = "--check" in sys.argv[1:]
    stale = []
    for name, text in (("CodePageTables.h", code_pages_header()), ("LetterFoldTable.h", letter_fold_header())):
        path = os.path.join(SRC, name)
        if check:
            try:
                now = io.open(path, encoding="utf-8", newline="").read().replace("\r\n", "\n")
            except OSError:
                now = None
            if now != text:
                stale.append(name)
        else:
            with io.open(path, "w", encoding="utf-8", newline="\n") as out:
                out.write(text)
            print("wrote", path)
    if stale:
        print("out of date: " + ", ".join(stale) + " (run SKSE/tools/gen_text_tables.py)")
        return 1
    if check:
        print("text tables are up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
